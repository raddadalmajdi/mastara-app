/**
 * معاملات عتبة "Sauvola" التكيّفية المحلية (Local Adaptive Thresholding) —
 * بديل حقيقي عن عتبة Otsu العامة الواحدة: تُحسَب عتبة مختلفة لكل بكسل بناءً
 * على متوسط والانحراف المعياري لجيرانه المباشرين فقط، فتحافظ على ضربات
 * الحروف الرفيعة/الباهتة (لا تُطبَّق عليها نفس الصرامة العامة التي كانت
 * تُطبَّق سابقاً لتنظيف الخلفية) بينما تُبقي الخلفية المسطّحة بيضاء نقية —
 * لأن التباين المحلي في مناطق الخلفية منخفض أصلاً فتنخفض عتبتها تلقائياً.
 *
 *   T(x,y) = mean(x,y) × (1 + k × (stddev(x,y)/R − 1))
 *
 * `SAUVOLA_K`: حساسية العتبة تجاه التباين المحلي (0.2–0.5 نموذجياً). قيمة
 * أعلى تعني الاحتفاظ بحبر أكثر (حروف أكثر اكتمالاً وسماكة) على حساب مخاطرة
 * أعلى قليلاً بضجيج في خلفية غير نظيفة تماماً.
 * `SAUVOLA_R`: المدى الديناميكي القياسي للانحراف المعياري لصور 8-bit.
 */
export const SAUVOLA_K = 0.32;
export const SAUVOLA_R = 128;

